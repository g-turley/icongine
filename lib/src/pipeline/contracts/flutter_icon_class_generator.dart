import 'dart:convert';

import 'package:dart_style/dart_style.dart';
import 'package:path/path.dart' as path;

import '../font/font_glyph.dart';

/// Generates a Flutter icon class file from compiled glyphs.
class FlutterIconClassGenerator {
  const FlutterIconClassGenerator({
    this.codeFormatter = const DartCodeFormatter(),
  });

  final DartCodeFormatter codeFormatter;

  String generate({
    required String className,
    required String fontFamily,
    required String fontPackage,
    required String outFontFile,
    required List<FontGlyph> glyphs,
    required bool staticIconProvider,
    required bool generateIconMap,
  }) {
    final buffer = StringBuffer()
      ..writeln('// Generated by icongine. Do not edit.')
      ..writeln('// ignore_for_file: unintended_html_in_doc_comment')
      ..writeln("import 'package:flutter/widgets.dart';")
      ..writeln()
      ..writeln('/// Identifiers for the icons in this font family.')
      ..writeln('///')
      ..writeln('/// Use with [Icon] or [IconButton], for example:')
      ..writeln('///')
      ..writeln('/// ```dart')
      ..writeln('/// Icon($className.${glyphs.firstOrNull?.name ?? 'icon'})')
      ..writeln('/// ```')
      ..writeln('///')
      ..writeln(
        "/// Ensure `pubspec.yaml` includes the `$fontFamily` font family:",
      )
      ..writeln('///')
      ..writeln('/// ```yaml')
      ..writeln('/// flutter:')
      ..writeln('///   fonts:')
      ..writeln('///     - family: $fontFamily')
      ..writeln(
        '///       fonts:\n///         - asset: ${_normalizeAssetPath(outFontFile)}',
      )
      ..writeln('/// ```');

    if (staticIconProvider) {
      buffer.writeln('@staticIconProvider');
    }

    buffer
      ..writeln('class $className {')
      ..writeln('  const $className._();')
      ..writeln("  static const String fontFamily = '$fontFamily';")
      ..writeln(
        "  static const String fontPackage = '${_escapeSingleQuoted(fontPackage)}';",
      );

    for (final glyph in glyphs) {
      final code = glyph.codePoint.toRadixString(16);
      buffer
        ..writeln()
        ..writeln("  /// Font icon named `${glyph.name}`.")
        ..write(_previewDoc(glyph.sourceSvgDocument))
        ..writeln(
          '  static const IconData ${glyph.name} = '
          'IconData(0x$code, fontFamily: fontFamily, fontPackage: fontPackage);',
        );
    }

    if (generateIconMap) {
      buffer.writeln();
      buffer.writeln('  static const Map<String, IconData> all = {');
      for (final glyph in glyphs) {
        buffer.writeln("    '${glyph.name}': ${glyph.name},");
      }
      buffer.writeln('  };');
    }
    buffer.writeln('}');

    return codeFormatter.format(buffer.toString());
  }

  String _previewDoc(String? svgContent) {
    if (svgContent == null || svgContent.trim().isEmpty) {
      return '';
    }
    final previewBase64 = base64Encode(utf8.encode(svgContent));
    return '''
  ///
  /// <image width="24" src="data:image/svg+xml;base64,$previewBase64" />
''';
  }

  String _normalizeAssetPath(String outFontFile) {
    final normalizedPath = path.normalize(outFontFile).replaceAll('\\', '/');
    return normalizedPath;
  }

  String _escapeSingleQuoted(String value) {
    return value.replaceAll("'", r"\'");
  }
}

/// Formatter abstraction to keep code generation testable.
class DartCodeFormatter {
  const DartCodeFormatter();

  String format(String source) {
    return DartFormatter(
      languageVersion: DartFormatter.latestLanguageVersion,
      pageWidth: 80,
    ).format(source);
  }
}
